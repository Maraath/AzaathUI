function text(img, x, y, s, col, scale = 2) {
	s = s.toUpperCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
	for (const ch of s) {
		const g = G[ch];
		if (g) g.split(" ").forEach((row, ry) => [...row].forEach((b, rx) => {
			if (b !== "1") return;
			for (let dy = 0; dy < scale; dy++) for (let dx = 0; dx < scale; dx++) {
				const px = x + rx * scale + dx, py = y + ry * scale + dy;
				if (px < 0 || py < 0 || px >= img.w || py >= img.h) continue;
				const i = (py * img.w + px) * 4; img.data[i] = col[0]; img.data[i + 1] = col[1]; img.data[i + 2] = col[2];
			}
		}));
		x += 6 * scale;
	}
}
